def classify(trait, landmarks):
    """특성 문장 + 랜드마크 문자열에서 아키타입을 추론한다."""
    text = f"{trait} {landmarks}"
    for arc, keys in _ARCHETYPE_RULES:
        if any(k in text for k in keys):
            return arc
    return "residential"


# ── 받침에 따른 조사 정리 ('X을(를)' → 하나로) ──────────────────────
_JOSA = {"을": "를", "은": "는", "이": "가", "과": "와", "아": "야", "으로": "로"}


def _has_final(ch):
    code = ord(ch)
    if 0xAC00 <= code <= 0xD7A3:
        return (code - 0xAC00) % 28 != 0
    return True  # 숫자·영문 등은 받침 있는 것으로 간주


def fix_particles(text):
    for fin, nofin in _JOSA.items():
        pat = re.compile(r"(.)" + re.escape(fin) + r"\(" + re.escape(nofin) + r"\)")
        text = pat.sub(
            lambda m: m.group(1) + (fin if _has_final(m.group(1)) else nofin), text
        )
    return text


def station_landmarks(name, feature):
    """역 특성 문장에서 랜드마크 후보를 최대 3개 뽑아 콤마 문자열로 만든다.

    역 데이터는 동과 달리 별도 랜드마크 목록이 없으므로, 특성 문장에서
    '·'·'과(와)'로 나열된 고유 명사를 추출하고, 모자라면 역명으로 채운다.
    """
    import re as _re
    # 명백한 격조사만 제거 — 고유명사에 흔한 '로/의/가/도' 등은 건드리지 않는다.
    _TAIL = ("을", "를", "은", "는")
    cand = []
    # '·'·','·'및'·'과 '·'와 ' 병렬 연결을 기준으로 명사구를 분리
    for chunk in _re.split(r"[·,]|과 |와 | 및 ", feature):
        mm = _re.match(r"[가-힣A-Za-z0-9]{2,10}", chunk.strip())
        if not mm:
            continue
        token = mm.group(0)
        for j in _TAIL:
            if token.endswith(j) and len(token) - len(j) >= 2:
                token = token[:-len(j)]
                break
        if token and token != name and token not in cand:
            cand.append(token)
        if len(cand) >= 3:
            break
    while len(cand) < 3:
        cand.append(f"{name} 일대")
    return ", ".join(cand[:3])


def split_landmarks(landmarks):
    parts = [p.strip() for p in landmarks.split(",") if p.strip()]
    while len(parts) < 3:
        parts.append(parts[-1] if parts else "인근 상권")
    return parts[0], parts[1], parts[2]


def _seed(slug):
    return sum((i + 1) * ord(c) for i, c in enumerate(slug))


def _alt(options, slug, salt):
    """아키타입 내부의 소규모 변형 — 지역마다 다른 표현을 고정 선택."""
    return options[(_seed(slug) + salt * 37 + len(slug) * 11) % len(options)]


